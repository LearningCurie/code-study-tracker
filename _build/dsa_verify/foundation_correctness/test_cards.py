import itertools
import math
import random
import re
import unittest
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2] / "dsa"
FILES = {
    "03-recur.cards.md": {
        "509": "fibonacci",
        "344": "reverse_chars",
        "231": "is_power_of_two",
        "326": "is_power_of_three",
        "779": "kth_symbol",
        "1922": "count_good_numbers",
        "241": "different_results",
    },
    "04-correct.cards.md": {
        "27": "remove_element",
        "26": "remove_duplicates",
        "58": "last_word_length",
        "66": "plus_one",
        "1299": "replace_with_right_max",
        "374": "guess_number",
    },
}


def load_cards():
    solutions = {}
    for filename, names in FILES.items():
        chunks = re.split(r"(?m)^=== card \| (\S+)\s*\n", (ROOT / filename).read_text())
        if chunks[0].strip():
            raise AssertionError(f"{filename}: unexpected text before cards")
        seen = set()
        for pid, card in zip(chunks[1::2], chunks[2::2]):
            if pid not in names or pid in seen:
                raise AssertionError(f"{filename}: unexpected or repeated card {pid}")
            seen.add(pid)
            blocks = re.findall(r"```python\n(.*?)\n```", card, re.S)
            if len(blocks) != 1 or "## Code\n" not in card:
                raise AssertionError(f"{filename} {pid}: expected one displayed Python block")
            namespace = {}
            exec(compile(blocks[0], f"{filename}:{pid}", "exec"), namespace)
            solutions[pid] = namespace[names[pid]]
        if seen != set(names):
            raise AssertionError(f"{filename}: missing cards {set(names) - seen}")
    return solutions


SOLVE = load_cards()


def tree_shapes(leaves):
    shapes = [None]
    for _ in range(leaves - 1):
        expanded = set()

        def grow(tree):
            if tree is None:
                return [(None, None)]
            left, right = tree
            return ([(child, right) for child in grow(left)] +
                    [(left, child) for child in grow(right)])

        for shape in shapes:
            expanded.update(grow(shape))
        shapes = list(expanded)
    return shapes


def expression_oracle(numbers, operators):
    results = []
    for shape in tree_shapes(len(numbers)):
        values = iter(numbers)
        ops = iter(operators)

        def render(node):
            if node is None:
                return str(next(values))
            left = render(node[0])
            op = next(ops)
            right = render(node[1])
            return f"({left}{op}{right})"

        # The tokens are generated by this test, never read from a card.
        results.append(eval(render(shape), {"__builtins__": {}}))
    return sorted(results)


class FoundationCards(unittest.TestCase):
    def test_fibonacci(self):
        values = [0, 1]
        for _ in range(500):
            values.append(sum(values[-2:]))
        for n, expected in enumerate(values):
            self.assertEqual(SOLVE["509"](n), expected)

    def test_reverse_chars(self):
        for n in range(8):
            for values in itertools.product("abc", repeat=n):
                actual = list(values)
                self.assertIsNone(SOLVE["344"](actual))
                self.assertEqual(actual, list(reversed(values)))

    def test_powers(self):
        for pid, base in (("231", 2), ("326", 3)):
            powers = {base ** i for i in range(32)}
            for n in itertools.chain(range(-1000, 10001),
                                     (2**31 - 1, -(2**31), *powers),
                                     (p - 1 for p in powers), (p + 1 for p in powers)):
                self.assertEqual(SOLVE[pid](n), n in powers, (pid, n))

    def test_kth_symbol(self):
        row = "0"
        for n in range(1, 13):
            for k, expected in enumerate(row, 1):
                self.assertEqual(SOLVE["779"](n, k), int(expected), (n, k))
            row = "".join("01" if bit == "0" else "10" for bit in row)
        rng = random.Random(779)
        for _ in range(2000):
            n = rng.randint(1, 30)
            k = rng.randint(1, 2 ** (n - 1))
            self.assertEqual(SOLVE["779"](n, k), (k - 1).bit_count() % 2, (n, k))

    def test_count_good_numbers(self):
        for n in range(6):
            expected = sum(
                all(d in ({0, 2, 4, 6, 8} if i % 2 == 0 else {2, 3, 5, 7})
                    for i, d in enumerate(digits))
                for digits in itertools.product(range(10), repeat=n)
            )
            self.assertEqual(SOLVE["1922"](n), expected)
        rng = random.Random(1922)
        mod = 1_000_000_007
        for n in [1, 2, 10**15] + [rng.randrange(10**15 + 1) for _ in range(1000)]:
            expected = pow(5, (n + 1) // 2, mod) * pow(4, n // 2, mod) % mod
            self.assertEqual(SOLVE["1922"](n), expected, n)

    def test_different_results(self):
        rng = random.Random(241)
        examples = [([2, 1, 1], ["-", "-"]), ([11, 2, 3], ["*", "-"]),
                    ([1, 1, 1, 1], ["+", "+", "+"])]
        for _ in range(1000):
            n = rng.randrange(1, 7)
            examples.append(([rng.randrange(20) for _ in range(n)],
                             [rng.choice("+-*") for _ in range(n - 1)]))
        for numbers, operators in examples:
            expression = "".join(str(x) + op for x, op in zip(numbers, operators)) + str(numbers[-1])
            self.assertEqual(sorted(SOLVE["241"](expression)),
                             expression_oracle(numbers, operators), expression)

    def test_remove_element(self):
        for n in range(7):
            for values in itertools.product(range(3), repeat=n):
                for target in range(4):
                    actual = list(values)
                    size = SOLVE["27"](actual, target)
                    expected = [x for x in values if x != target]
                    self.assertEqual(size, len(expected), (values, target))
                    self.assertEqual(actual[:size], expected, (values, target))
                    self.assertEqual(len(actual), n)

    def test_remove_duplicates(self):
        for n in range(9):
            for values in itertools.combinations_with_replacement(range(-2, 3), n):
                actual = list(values)
                size = SOLVE["26"](actual)
                expected = sorted(set(values))
                self.assertEqual(size, len(expected), values)
                self.assertEqual(actual[:size], expected, values)
                self.assertEqual(len(actual), n)

    def test_last_word(self):
        for n in range(9):
            for chars in itertools.product("ab ", repeat=n):
                text = "".join(chars)
                words = text.split()
                self.assertEqual(SOLVE["58"](text), len(words[-1]) if words else 0, text)

    def test_plus_one(self):
        for number in range(20000):
            digits = [int(x) for x in str(number)]
            expected = [int(x) for x in str(number + 1)]
            self.assertEqual(SOLVE["66"](digits), expected, number)
        for n in (1, 2, 10, 100):
            self.assertEqual(SOLVE["66"]([9] * n), [1] + [0] * n)
            self.assertEqual(SOLVE["66"]([1] + [9] * (n - 1)),
                             [2] + [0] * (n - 1))

    def test_right_max(self):
        for n in range(8):
            for values in itertools.product(range(1, 5), repeat=n):
                actual = list(values)
                result = SOLVE["1299"](actual)
                expected = [max(values[i + 1:]) if i + 1 < n else -1 for i in range(n)]
                self.assertIs(result, actual)
                self.assertEqual(actual, expected, values)

    def test_guess_number(self):
        def check(n, hidden):
            guesses = []

            def guess(value):
                self.assertTrue(1 <= value <= n)
                guesses.append(value)
                return (hidden > value) - (hidden < value)

            self.assertEqual(SOLVE["374"](n, guess), hidden, (n, hidden, guesses))
            self.assertLessEqual(len(guesses), math.ceil(math.log2(n)) if n > 1 else 0)

        for n in range(1, 201):
            for hidden in range(1, n + 1):
                check(n, hidden)
        rng = random.Random(374)
        for _ in range(1000):
            n = rng.randint(1, 2**31 - 1)
            check(n, rng.randint(1, n))
        for hidden in (1, 2, 2**30, 2**31 - 2, 2**31 - 1):
            check(2**31 - 1, hidden)


if __name__ == "__main__":
    unittest.main()
